"""Generate docs/model_evaluation_report.md from the registered model artifacts.

    python scripts/make_report.py

Every number in the report is read from artifacts/models/*/<version>/metrics.json etc.,
i.e. from models trained and evaluated on the ingested data. Nothing is typed by hand."""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.common.config import get_settings  # noqa: E402
from src.models.registry import latest_dir, load_json  # noqa: E402


def f(v, d=3):
    return "—" if v is None else (f"{v:,.{d}f}" if isinstance(v, (int, float)) else str(v))


def main() -> None:
    root = get_settings().models_dir
    tasks = sorted(p.name for p in root.iterdir() if p.is_dir() and latest_dir(p.name)) if root.exists() else []
    lines = ["# Model evaluation report", "",
             "_Generated by `scripts/make_report.py` from registered model artifacts. "
             "All metrics are on a chronologically held-out test period._", ""]
    if not tasks:
        lines.append("No trained models found. Run `python -m src.pipeline all` first.")
    for t in tasks:
        m = load_json(t, "metrics")
        meta = load_json(t, "metadata") or {}
        fc = load_json(t, "feature_config") or {}
        if not m:
            continue
        lines += [f"## {t}", ""]
        if "best_model" not in m:   # classical forecasting summary
            lines += ["| model · horizon | MAE | RMSE | R² |", "|---|---|---|---|"]
            for k, v in (m.get("aggregate") or {}).items():
                lines.append(f"| {k} | {f(v.get('mae'))} | {f(v.get('rmse'))} | {f(v.get('r2'))} |")
            lines.append("")
            continue
        sp = m["split"]
        lines += [f"- Source: {meta.get('source', '—')}  ",
                  f"- Version: `{latest_dir(t).name}` · best model: **{m['best_model']}** (selected on validation score)  ",
                  f"- Rows: train {sp['train_rows']:,} · valid {sp['valid_rows']:,} · test {sp['test_rows']:,}  ",
                  f"- Test period: {sp['test_period'][0]} → {sp['test_period'][1]}", ""]
        clf = fc.get("kind") == "clf"
        keys = ["f1_macro", "accuracy", "roc_auc_ovr_macro"] if clf else ["mae", "rmse", "r2", "mape_pct"]
        lines += ["| candidate | " + " | ".join(keys) + " | CV mean ± sd |", "|---" * (len(keys) + 2) + "|"]
        for name, r in m["models"].items():
            star = " ★" if name == m["best_model"] else ""
            lines.append(f"| {name}{star} | " + " | ".join(f(r['test'].get(k)) for k in keys)
                         + f" | {f(r['cv_mean'])} ± {f(r['cv_std'])} |")
        for name, r in m.get("baselines", {}).items():
            lines.append(f"| _baseline: {name}_ | " + " | ".join(f(r.get(k)) for k in keys) + " | |")
        iv = load_json(t, "intervals")
        if iv:
            lines += ["", f"80% prediction interval empirical coverage on test: **{iv['empirical_test_coverage']:.1%}**"]
        imp = load_json(t, "shap") or {}
        if imp.get("mean_abs_shap"):
            top = ", ".join(r["feature"] for r in imp["mean_abs_shap"][:8])
            lines += ["", f"Top features by mean |SHAP|: {top}"]
        lines.append("")
    out = ROOT / "docs" / "model_evaluation_report.md"
    out.write_text("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main()
